// Genera meses desde 6 meses atrás hasta el PRÓXIMO mes relativo al actual (M + 1)
function getAvailableMonths(): { value: string; label: string }[] {
  const now = new Date();
  const currentYear = now.getFullYear();
  const currentMonth = now.getMonth();
  const nombresMeses = [
    'Enero', 'Febrero', 'Marzo', 'Abril', 'Mayo', 'Junio',
    'Julio', 'Agosto', 'Septiembre', 'Octubre', 'Noviembre', 'Diciembre'
  ];

  const months: { value: string; label: string }[] = [];
  // Desde 6 meses atrás hasta el próximo mes (i = 1)
  for (let i = -6; i <= 1; i++) {
    const d = new Date(currentYear, currentMonth + i, 1);
    const y = d.getFullYear();
    const m = String(d.getMonth() + 1).padStart(2, '0');
    months.push({
      value: `${y}-${m}`,
      label: `${nombresMeses[d.getMonth()]} ${y}`
    });
  }
  return months;
}

