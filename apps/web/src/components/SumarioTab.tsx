  const handleDragStart = (e: React.DragEvent, id: string) => {
    e.dataTransfer.setData('text/plain', id);
    e.dataTransfer.effectAllowed = 'move';
    setDraggedRowId(id);
  };

  const handleDragOver = (e: React.DragEvent, id: string) => {
    e.preventDefault();
    e.dataTransfer.dropEffect = 'move';
    if (dragOverRowId !== id) {
      setDragOverRowId(id);
    }
  };

  const handleDrop = (e: React.DragEvent, dropTargetId: string, currentCategoryRows: SumarioRow[]) => {
    e.preventDefault();
    const sourceId = e.dataTransfer.getData('text/plain') || draggedRowId;
    if (!sourceId || sourceId === dropTargetId) return;

    const sourceIndex = currentCategoryRows.findIndex(r => r.id === sourceId);
    const dropIndex = currentCategoryRows.findIndex(r => r.id === dropTargetId);
    if (sourceIndex === -1 || dropIndex === -1) return;

    const updated = [...currentCategoryRows];
    const [movedItem] = updated.splice(sourceIndex, 1);
    updated.splice(dropIndex, 0, movedItem);

    const newMap = { ...rowSortOrder };
    updated.forEach((r, idx) => {
      newMap[r.id] = idx;
    });

    setRowSortOrder(newMap);
    setDraggedRowId(null);
    setDragOverRowId(null);
  };

